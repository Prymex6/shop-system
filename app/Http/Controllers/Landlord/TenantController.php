    public function update(Request $request, Tenant $tenant)
    {
        $validated = $request->validate([
            'name' => ['required', 'string', 'max:255'],
            'plan_id' => ['nullable', 'exists:plans,id'],
            'status' => ['required', 'in:active,suspended'],
            'version' => ['required', 'in:stable,test'],
            'license_ends_at' => ['nullable', 'date'],
        ]);

        $tenant->update($validated);

        return redirect()->route('landlord.tenants.index')
            ->with('success', "Sklep '{$tenant->name}' został zaktualizowany!");
    }

    /**
     * Does NOT drop the database. A real shop's entire database (orders,
     * customers, everything) is too costly to lose to a mis-click, a
     * replayed request, or a compromised super-admin session — this only
     * flags the tenant for deletion. The actual DeleteDatabase pipeline
     * runs later, from the `tenants:prune-pending-deletion` scheduled
     * command, once the grace period in that command has passed. Until
     * then a super-admin can call cancelDeletion() to undo this completely.
     */
    public function destroy(Request $request, Tenant $tenant)
    {
        $request->validate([
            'confirm_name' => ['required', 'string'],
        ]);

        if ($request->confirm_name !== $tenant->name) {
            return back()->withErrors(['confirm_name' => 'Wpisana nazwa nie zgadza się z nazwą sklepu.']);
        }

        $tenant->update([
            'status' => 'pending_deletion',
            'deletion_requested_at' => now(),
        ]);

        return redirect()->route('landlord.tenants.index')
            ->with('success', "Sklep '{$tenant->name}' zostanie trwale usunięty za 7 dni. Możesz to cofnąć do tego czasu.");
    }

    /**
     * Undo a pending deletion (only possible before the grace period elapses
     * and the scheduled prune command has actually dropped the database).
     */
    public function cancelDeletion(Tenant $tenant)
    {
        if ($tenant->status !== 'pending_deletion') {
            return back()->with('error', __('messages.shop_not_marked_for_deletion'));
        }

        $tenant->update([
            'status' => 'active',
            'deletion_requested_at' => null,
        ]);

        return back()->with('success', "Usunięcie sklepu '{$tenant->name}' zostało anulowane.");
    }

