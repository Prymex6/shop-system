    /**
     * Generate impersonation token and redirect to tenant's manager panel.
     */
    public function impersonate(Tenant $tenant)
    {
        // Find first manager user in the tenant's DB
        tenancy()->initialize($tenant);
        $manager = User::where('role', 'manager')->first();
        tenancy()->end();

        if (!$manager) {
            return back()->withErrors(['error' => 'Brak konta managera w tym sklepie.']);
        }

        // Generate short-lived token stored in cache (5 minutes)
        $token = Str::random(40);
        // Use file store explicitly to bypass CacheTenancyBootstrapper (database store doesn't support tags)
        Cache::store('file')->put('impersonate:' . $token, [
            'tenant_id' => $tenant->id,
            'user_id' => $manager->id,
        ], now()->addMinutes(5));

        $parsed = parse_url(config('app.url', 'http://localhost'));
        $scheme = app()->environment('production') ? 'https' : ($parsed['scheme'] ?? 'http');
        $baseDomain = config('tenancy.base_domain');
        $port = isset($parsed['port']) ? ':' . $parsed['port'] : '';
        $targetUrl = $scheme . '://' . $tenant->subdomain . '.' . $baseDomain . $port . '/manager/impersonate?token=' . $token;

        return redirect()->away($targetUrl);
    }
