    public function store(Request $request)
    {
        // Computed once up front, so the uniqueness check below validates the
        // exact value that will actually be inserted into domains.domain
        // (e.g. "acme.storelo.pl"), not the bare subdomain ("acme") — the old
        // 'unique:domains,domain' rule checked the wrong column value and
        // essentially never fired, so a colliding subdomain reached
        // domains()->create() and threw an uncaught 500 after the tenant row
        // (and its real database) had already been created.
        $baseDomain = config('tenancy.base_domain') ?: (config('tenancy.central_domains')[0] ?? 'localhost');
        $baseDomain = preg_replace('/:\d+$/', '', $baseDomain); // strip port

        $validated = $request->validate([
            'name' => ['required', 'string', 'max:255'],
            'subdomain' => [
                'required', 'string', 'max:255', 'alpha_dash',
                Rule::unique('domains', 'domain')->using(function ($query) use ($baseDomain, $request) {
                    $query->where('domain', $request->input('subdomain') . '.' . $baseDomain);
                }),
            ],
            'plan_id' => ['nullable', 'exists:plans,id'],
            'status' => ['required', 'in:active,suspended'],
            'version' => ['required', 'in:stable,test'],
            'license_ends_at' => ['nullable', 'date'],
            'owner_name' => ['nullable', 'string', 'max:255'],
            'owner_email' => ['nullable', 'email', 'max:255'],
        ]);

        // Create tenant (ID will be auto-generated by stancl/tenancy)
        $tenant = Tenant::create([
            'name' => $validated['name'],
            'subdomain' => $validated['subdomain'],
            'plan_id' => $validated['plan_id'] ?? null,
            'status' => $validated['status'],
            'version' => $validated['version'],
            'license_ends_at' => $validated['license_ends_at'] ?? null,
        ]);

        // Create domain
        $tenant->domains()->create([
            'domain' => $validated['subdomain'] . '.' . $baseDomain,
        ]);

        // Add the DNS record in Cloudflare, when one is configured
        $cloudflare = app(CloudflareService::class);
        if ($cloudflare->isConfigured()) {
            $dnsRecordId = $cloudflare->addSubdomain($validated['subdomain']);
            if ($dnsRecordId) {
                $tenant->update(['data->cloudflare_dns_id' => $dnsRecordId]);
            }
        }

        // Always migrate the tenant database immediately after creation.
        Artisan::call('tenants:migrate', [
            '--tenants' => [$tenant->id],
            '--force' => true,
        ]);

        // Always seed default settings and permissions
        try {
            tenancy()->initialize($tenant);
            $this->seedDefaultRolePermissions();
            $this->seedDefaultSettings($validated['name']);
            tenancy()->end();
        } catch (\Exception $e) {
            Log::error('Failed to seed default settings: ' . $e->getMessage());
            if (tenancy()->initialized) {
                tenancy()->end();
            }
        }

        // Create initial manager account and send welcome email (#23)
        if (!empty($validated['owner_email'])) {
            try {
                $password = Str::random(12);
                $ownerName = $validated['owner_name'] ?? 'Manager';
                $ownerEmail = $validated['owner_email'];

                tenancy()->initialize($tenant);

                User::create([
                    'name' => $ownerName,
                    'email' => $ownerEmail,
                    'password' => Hash::make($password),
                    'role' => 'manager',
                ]);

                tenancy()->end();

                $scheme = app()->environment('production') ? 'https' : 'http';
                $loginUrl = $scheme . '://' . $validated['subdomain'] . '.' . $baseDomain . '/login';

                Mail::to($ownerEmail)->queue(new TenantWelcomeMail(
                    ownerName: $ownerName,
                    shopName: $validated['name'],
                    loginUrl: $loginUrl,
                    password: $password,
                    email: $ownerEmail,
                ));
            } catch (\Exception $e) {
                Log::error('Failed to create tenant manager: ' . $e->getMessage());
                if (tenancy()->initialized) {
                    tenancy()->end();
                }
            }
        }

        $redirect = redirect()->route('landlord.tenants.index')
            ->with('success', "Sklep '{$tenant->name}' został utworzony!");

        if (isset($password)) {
            $redirect = $redirect
                ->with('generated_password', $password)
                ->with('generated_password_email', $validated['owner_email']);
        }

        return $redirect;
    }

